-- Gobernanza: propuestas con aprobación humana, memoria y señal DPO.

CREATE TABLE perfiles (
    usuario TEXT PRIMARY KEY,
    rol TEXT NOT NULL,
    equipo TEXT,
    preferencias JSONB
);

COMMENT ON TABLE perfiles IS
  'Perfil del coordinador que usa el chat (rol, equipo, preferencias).';

CREATE TABLE conversaciones (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    usuario TEXT NOT NULL,
    iniciado_en TIMESTAMPTZ NOT NULL DEFAULT now()
);

COMMENT ON TABLE conversaciones IS 'Hilos de chat; agrupan mensajes y propuestas.';

CREATE TABLE mensajes (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    conversacion_id UUID NOT NULL REFERENCES conversaciones (id),
    rol TEXT NOT NULL CHECK (rol IN ('user', 'assistant', 'tool')),
    contenido JSONB NOT NULL,
    creado_en TIMESTAMPTZ NOT NULL DEFAULT now()
);

COMMENT ON TABLE mensajes IS 'Historial de la conversación (usuario, asistente, tools).';

CREATE TABLE propuestas (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    conversacion_id UUID NULL REFERENCES conversaciones (id),
    usuario TEXT NOT NULL,
    orden_texto TEXT NOT NULL,
    extraccion JSONB,
    acciones JSONB,
    veredicto_auditor JSONB,
    estado TEXT NOT NULL CHECK (
        estado IN ('pendiente', 'aprobada', 'corregida', 'rechazada', 'expirada')
    ),
    creado_en TIMESTAMPTZ NOT NULL DEFAULT now(),
    decidido_en TIMESTAMPTZ
);

COMMENT ON TABLE propuestas IS
  'Tarjeta de escritura: lo que muestra es exactamente lo que se puede escribir.';
COMMENT ON COLUMN propuestas.extraccion IS 'JSON del extractor de órdenes.';
COMMENT ON COLUMN propuestas.acciones IS
  'Acciones congeladas que mostrará la tarjeta y ejecutará el backend.';
COMMENT ON COLUMN propuestas.veredicto_auditor IS
  'Veredicto A2A completo del auditor (aprobado, observaciones o rechazado).';

CREATE TABLE aprobaciones (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    propuesta_id UUID NOT NULL REFERENCES propuestas (id),
    usuario TEXT NOT NULL,
    decision TEXT NOT NULL CHECK (decision IN ('aprobar', 'corregir', 'rechazar')),
    correccion JSONB NULL,
    creado_en TIMESTAMPTZ NOT NULL DEFAULT now()
);

COMMENT ON TABLE aprobaciones IS
  'Decisión humana sobre una propuesta. Es el permiso de escritura.';
COMMENT ON COLUMN aprobaciones.correccion IS
  'Acciones corregidas por el humano cuando decision=corregir.';

CREATE TABLE pares_preferencia (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    propuesta_id UUID NOT NULL REFERENCES propuestas (id),
    prompt_texto TEXT NOT NULL,
    elegida JSONB,
    rechazada JSONB,
    origen TEXT NOT NULL CHECK (origen IN ('aprobacion', 'correccion', 'rechazo')),
    usado_en_version TEXT NULL,
    creado_en TIMESTAMPTZ NOT NULL DEFAULT now()
);

COMMENT ON TABLE pares_preferencia IS
  'Señal de entrenamiento DPO: (propuesta, decisión humana).';
COMMENT ON COLUMN pares_preferencia.elegida IS
  'Extracción correcta (aprobada o corregida).';
COMMENT ON COLUMN pares_preferencia.rechazada IS
  'Extracción original cuando fue corregida o rechazada.';

ALTER TABLE asignaciones
    ADD CONSTRAINT asignaciones_propuesta_id_fkey
    FOREIGN KEY (propuesta_id) REFERENCES propuestas (id);

ALTER TABLE ausencias
    ADD CONSTRAINT ausencias_propuesta_id_fkey
    FOREIGN KEY (propuesta_id) REFERENCES propuestas (id);
