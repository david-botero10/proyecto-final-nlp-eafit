-- Corpus normativo: documentos y chunks con embedding bge-m3 y tsvector.

CREATE TABLE documentos (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    titulo TEXT NOT NULL,
    fuente TEXT NOT NULL,
    tipo TEXT NOT NULL CHECK (tipo IN ('ley', 'decreto', 'cartilla')),
    url TEXT,
    fecha_descarga DATE,
    hash_sha256 TEXT,
    vigencia TEXT
);

COMMENT ON TABLE documentos IS
  'Fuentes normativas públicas (CST, cartillas MinTrabajo, leyes de jornada).';
COMMENT ON COLUMN documentos.hash_sha256 IS
  'Hash del archivo descargado; la reindexación es idempotente por hash.';

CREATE TABLE chunks (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    documento_id INTEGER NOT NULL REFERENCES documentos (id),
    ref TEXT,
    texto TEXT NOT NULL,
    metadatos JSONB,
    embedding vector(1024),
    tsv tsvector GENERATED ALWAYS AS (
        to_tsvector('spanish', es_unaccent(texto))
    ) STORED
);

COMMENT ON TABLE chunks IS
  'Fragmentos indexados: un artículo de ley o una sección de cartilla.';
COMMENT ON COLUMN chunks.ref IS 'Referencia humana, p. ej. art. 168.';
COMMENT ON COLUMN chunks.embedding IS 'Vector bge-m3 de 1024 dimensiones.';
COMMENT ON COLUMN chunks.tsv IS
  'tsvector español con unaccent inmutable para búsqueda léxica.';

CREATE INDEX idx_chunks_embedding_hnsw
    ON chunks USING hnsw (embedding vector_cosine_ops);

CREATE INDEX idx_chunks_tsv_gin
    ON chunks USING gin (tsv);
