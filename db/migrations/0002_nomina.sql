-- Nómina sintética: catálogo de turnos, empleados, asignaciones y ausencias.
-- propuesta_id se declara aquí; la FK a propuestas se añade en 0003_gobernanza.sql.

CREATE TABLE turnos (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo CHAR(1) NOT NULL UNIQUE,
    nombre TEXT NOT NULL,
    hora_inicio TIME NOT NULL,
    hora_fin TIME NOT NULL,
    cruza_medianoche BOOLEAN NOT NULL
);

COMMENT ON TABLE turnos IS
  'Catálogo de turnos de la clínica simulada (M mañana, T tarde, N noche).';
COMMENT ON COLUMN turnos.codigo IS 'Código de un carácter: M, T o N.';
COMMENT ON COLUMN turnos.cruza_medianoche IS
  'Verdadero si el turno termina al día siguiente (turno noche).';

CREATE TABLE empleados (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre TEXT NOT NULL,
    documento TEXT NOT NULL UNIQUE,
    rol TEXT NOT NULL,
    equipo TEXT NOT NULL,
    fecha_ingreso DATE NOT NULL,
    activo BOOLEAN NOT NULL
);

COMMENT ON TABLE empleados IS
  'Empleados sintéticos (Faker es_CO). No contiene datos de personas reales.';
COMMENT ON COLUMN empleados.documento IS 'Cédula ficticia, única.';
COMMENT ON COLUMN empleados.equipo IS
  'equipo: enfermeria, recepcion o vigilancia.';

CREATE TABLE asignaciones (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    empleado_id INTEGER NOT NULL REFERENCES empleados (id),
    turno_id INTEGER NOT NULL REFERENCES turnos (id),
    fecha DATE NOT NULL,
    estado TEXT NOT NULL CHECK (estado IN ('programada', 'completada', 'cancelada')),
    origen TEXT NOT NULL CHECK (origen IN ('seed', 'tarjeta')),
    propuesta_id UUID NULL,
    creado_en TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (empleado_id, fecha, turno_id)
);

CREATE INDEX idx_asignaciones_empleado_fecha
    ON asignaciones (empleado_id, fecha);

COMMENT ON TABLE asignaciones IS
  'Turno asignado a un empleado en una fecha. origen=tarjeta solo tras aprobación.';
COMMENT ON COLUMN asignaciones.origen IS
  'seed = dataset inicial; tarjeta = escrito por ejecutar_propuesta.';
COMMENT ON COLUMN asignaciones.propuesta_id IS
  'Propuesta aprobada que originó la fila; nulo en el seed.';

CREATE TABLE ausencias (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    empleado_id INTEGER NOT NULL REFERENCES empleados (id),
    tipo TEXT NOT NULL CHECK (
        tipo IN ('vacaciones', 'incapacidad', 'permiso', 'licencia')
    ),
    fecha_inicio DATE NOT NULL,
    fecha_fin DATE NOT NULL,
    estado TEXT NOT NULL CHECK (estado IN ('aprobada', 'pendiente', 'rechazada')),
    motivo TEXT,
    propuesta_id UUID NULL,
    creado_en TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX idx_ausencias_empleado_fecha
    ON ausencias (empleado_id, fecha_inicio);

COMMENT ON TABLE ausencias IS
  'Ausencias sintéticas. Las aprobadas no se solapan con asignaciones activas.';
COMMENT ON COLUMN ausencias.propuesta_id IS
  'Propuesta que originó la ausencia; nulo en el seed.';
