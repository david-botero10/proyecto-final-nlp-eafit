from __future__ import annotations

from dataclasses import dataclass


@dataclass(frozen=True)
class Molde:
    """Una frase con huecos y la etiqueta que le corresponde."""

    id: str
    grupo: str
    accion: str
    plantilla: str
    turno: str | None
    cuando: str
    turno_habla: str
    cuando_habla: str
    justificacion: str | None = None
    justi_habla: str | None = None
    genero: str | None = None


def _m(
    id_: str,
    grupo: str,
    accion: str,
    plantilla: str,
    turno: str | None,
    cuando: str,
    turno_habla: str,
    cuando_habla: str,
    justificacion: str | None = None,
    justi_habla: str | None = None,
    genero: str | None = None,
) -> Molde:
    return Molde(
        id=id_,
        grupo=grupo,
        accion=accion,
        plantilla=plantilla,
        turno=turno,
        cuando=cuando,
        turno_habla=turno_habla,
        cuando_habla=cuando_habla,
        justificacion=justificacion,
        justi_habla=justi_habla,
        genero=genero,
    )


